#!/usr/bin/env python3
"""Generate font_metrics.js: advance widths (per 1000 em) for the deck's fonts.

Calibri and Cambria are measured through their metric-compatible open twins
(Carlito and Caladea), which LibreOffice uses when rendering QA previews.
Run:  python3 tools/gen_font_metrics.py > font_metrics.js
"""
import json
import sys
from PIL import ImageFont

FONTS = {
    "Calibri": ("Carlito-Regular", "Carlito-Bold"),
    "Cambria": ("Caladea-Regular", "Caladea-Bold"),
}
DIR = "/usr/share/fonts/truetype/crosextra/"
EXTRA = "₹–—‘’“”…×≥≤→←↑↓·•≈±°½¼¾€£§©®™√∆"
CHARS = "".join(chr(c) for c in range(32, 127)) + EXTRA

out = {}
for name, (reg, bold) in FONTS.items():
    entry = {}
    for style, fname in (("regular", reg), ("bold", bold)):
        f = ImageFont.truetype(DIR + fname + ".ttf", 1000)
        asc, desc = f.getmetrics()
        widths = {ch: round(f.getlength(ch), 1) for ch in CHARS}
        entry[style] = {"widths": widths, "lineHeight": round((asc + desc) / 1000, 3)}
    out[name] = entry

sys.stdout.write("// Generated by tools/gen_font_metrics.py: do not edit by hand.\n")
sys.stdout.write("// Advance widths per 1000 em for Calibri (Carlito) and Cambria (Caladea).\n")
sys.stdout.write("module.exports = " + json.dumps(out, ensure_ascii=False) + ";\n")
